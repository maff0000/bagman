"""SQLAlchemy table definition for BAGMAN's durable `operator_sessions`
table (WO-BAGMAN-117 §6.A.7, PID §117.C).

Kept as its own module rather than added to
`persistence/postgres/models.py` — the exact same precedent
`background_job_models.py`/`needs_you_models.py` already set (see
`background_job_models.py`'s own module docstring: "a new bounded-
component table gets its own module"). Shares the same declarative
`Base` (imported from `persistence.postgres.models`) so this table
still lives in the one `MetaData`/Alembic target every other table
does.

Not registered in `alembic/env.py`'s own explicit model-import list
------------------------------------------------------------------------
`alembic/env.py` imports a handful of these per-domain model modules
explicitly so `alembic revision --autogenerate` can see their tables
(`intake_models`, `ai_invocation_models`, `xero_models`,
`evidence_classification_rule_models`, `evidence_classification_models`).
It does NOT currently import `needs_you_models` or
`background_job_models` — `alembic/env.py`'s own docstring flags the
`needs_you_models` gap explicitly as pre-existing and out of its
authoring WI's scope to fix. This migration's own `upgrade()`/
`downgrade()` are hand-written (mirroring `9c2f4b1e7a05_needs_you_items.py`
and `c7a3f9e1b542_inference_backend_and_background_jobs.py`, neither of
which required an `env.py` registration either to apply correctly via
`alembic upgrade head`) rather than autogenerated, so this is a real,
working table despite not being wired into that one autogenerate
convenience list. This WO's own file-scope is deliberately narrow
(WO-BAGMAN-117 §6.A's enumerated file list does not include
`alembic/env.py`) — this module follows the SAME already-accepted,
already-shipped precedent (`needs_you_models`/`background_job_models`)
rather than opening a second, unrelated file to close a pre-existing,
explicitly-documented gap this delivery did not create.

Security note (PID §117.C)
------------------------------------------------------------------------
`token_digest` is a SHA-256 hex digest (`core.auth.hash_token`) — the
raw session token is NEVER a column on this table, NEVER logged, and
NEVER appears anywhere in this module. `token_digest` doubles as the
table's own primary key (mirroring `persistence/postgres/xero_models.py`'s
`XeroOAuthStateRow.state`-as-PK precedent for an equivalent ephemeral,
token-identified security record) — a 256-bit, cryptographically
random digest needs no separate surrogate key.
"""
from __future__ import annotations

from datetime import datetime
from typing import Optional

import sqlalchemy as sa
from sqlalchemy import DateTime, Index, String
from sqlalchemy.orm import Mapped, mapped_column

from persistence.postgres.models import Base


class OperatorSessionRow(Base):
    """Persisted form of `core.auth.SessionRecord`."""

    __tablename__ = "operator_sessions"
    __table_args__ = (
        # Supports `revoke_all_sessions`'s bulk "every currently-active
        # session" update (PID §117.F password-reset revocation) without
        # a full-table scan once the table has accumulated a long
        # history of expired/revoked rows — a PARTIAL index, exactly
        # like `f7c3a58b1e9d`'s own partial-index precedent, scoped to
        # only the rows that query actually touches.
        Index(
            "ix_operator_sessions_active",
            "revoked_at",
            postgresql_where=sa.text("revoked_at IS NULL"),
        ),
    )

    token_digest: Mapped[str] = mapped_column(String(64), primary_key=True)
    csrf_token: Mapped[str] = mapped_column(String, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    revoked_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
